"""Create one episode folder: main.py stub, manim.cfg, shots.json skeleton.

An episode is a self-contained render unit. Manim resolves relative paths
against the working directory, so every episode keeps its own assets and its
own media/ output next to main.py.

    python scaffold_video.py --root C:\\manimwork\\my-paper --name ep01_problem \\
        --title "이 논문이 풀려는 문제" --scenes intro problem why

Scene names are CLI render targets, so keep them short, lowercase and ASCII.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

TEMPLATE_DIR = Path(__file__).resolve().parent.parent / "assets" / "project_template"

HEADER = '''"""{title}

Episode: {name}
Generated by paper-to-manim-video — edit freely, but keep the timing contract:
`playw` plays THEN waits, so a shot lasts run_time + wait, and
wait = max(0.2, est_sec - run_time) comes from shots.json.

Render a segment by class name (never bare `manim main.py` — several classes in
one file make Manim stop and ask):

{render_lines}
"""

from manim import *
from raenim import *
from random import seed


# Windows consoles default to cp949 here, and every one of these scripts prints
# Korean. Without this, a run dies with UnicodeEncodeError *after* it has already
# written its output files — the confusing failure mode of looking broken while
# actually having succeeded.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass

seed(41)
np.random.seed(41)

# Pango will not pick a Korean face on its own — always name one.
KR = "Malgun Gothic"


def kr(text: str, **kwargs) -> Text:
    """Korean text with the project font applied."""
    kwargs.setdefault("font", KR)
    return Text(text, **kwargs)


ASSETS = Path(__file__).parent / "assets"
'''

SCENE_STUB = '''

class {scene}(Scene2D):
    """{purpose}"""

    def construct(self):
        # TODO: shots for `{scene}` — one self.playw(...) per shot in shots.json.
        # self.playw(Write(kr("...")), run_time=1.2, wait=1.4)
        heading = kr("{scene}", font_size=36)
        self.playw(FadeIn(heading), run_time=1.0, wait=0.8)
'''


def safe_scene_name(name: str) -> str:
    cleaned = re.sub(r"[^0-9a-zA-Z_]", "_", name).strip("_")
    if not cleaned or cleaned[0].isdigit():
        cleaned = f"s_{cleaned}"
    return cleaned


def main() -> int:
    ap = argparse.ArgumentParser(description="에피소드 폴더 스캐폴딩")
    ap.add_argument("--root", required=True, help="프로젝트 루트 (venv가 있는 곳)")
    ap.add_argument("--name", required=True, help="에피소드 폴더명 (예: ep01_problem)")
    ap.add_argument("--title", required=True, help="에피소드 제목 (한국어 가능)")
    ap.add_argument("--scenes", nargs="+", required=True, help="구간 클래스명 (소문자 ASCII)")
    ap.add_argument("--force", action="store_true", help="기존 main.py를 덮어씀")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    episode = root / args.name
    episode.mkdir(parents=True, exist_ok=True)
    (episode / "assets" / "generated").mkdir(parents=True, exist_ok=True)
    (episode / "assets" / "figures").mkdir(parents=True, exist_ok=True)

    scenes = []
    for raw in args.scenes:
        safe = safe_scene_name(raw)
        if safe != raw:
            print(f"[scaffold] 씬 이름 보정: {raw!r} -> {safe!r}")
        scenes.append(safe)

    cfg_src = TEMPLATE_DIR / "manim.cfg"
    if cfg_src.is_file():
        shutil.copyfile(cfg_src, episode / "manim.cfg")
    else:
        print(f"[scaffold] 경고: 템플릿 manim.cfg를 찾지 못했습니다 ({cfg_src})")

    main_py = episode / "main.py"
    if main_py.exists() and not args.force:
        print(f"[scaffold] main.py가 이미 있습니다 — 건너뜁니다 (--force로 덮어쓰기)")
    else:
        render_lines = "\n".join(
            f"    uv run manim -ql main.py {s}" for s in scenes[:3]
        )
        body = HEADER.format(title=args.title, name=args.name, render_lines=render_lines)
        for s in scenes:
            body += SCENE_STUB.format(scene=s, purpose=f"{args.title} — {s} 구간")
        main_py.write_text(body, encoding="utf-8")
        print(f"[scaffold] {main_py}")

    shots_path = episode / "shots.json"
    if not shots_path.exists() or args.force:
        skeleton = {
            "video": args.name,
            "title": args.title,
            "scenes": {
                s: {"shots": [
                    {"id": f"{s}_s01", "narration": "", "visual": "", "code_hint": "",
                     "est_sec": 0, "run_time": 1.2, "wait": 0.2, "asset": None}
                ]} for s in scenes
            },
        }
        shots_path.write_text(json.dumps(skeleton, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"[scaffold] {shots_path}")

    print(f"[scaffold] 에피소드 준비 완료: {episode}")
    print(f"[scaffold] 다음: shots.json에 나레이션을 채우고 "
          f"estimate_narration.py --shots shots.json --write 를 실행하세요.")

    if args.json:
        print(json.dumps({"episode": str(episode), "scenes": scenes,
                          "main_py": str(main_py), "shots": str(shots_path)},
                         ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
