"""Create the uv-managed render environment for a video project.

Run with the *system* Python — it bootstraps the project venv itself.

    python setup_env.py --root C:\\manimwork\\my-paper [--force]

Why the install order is unusual
--------------------------------
raenim ships no `[build-system]`, so installers fall back to legacy setup.py,
whose `install_requires` lists `noise`. `noise` has no CPython 3.11 wheel and
needs MSVC to build. If raenim were a normal dependency in pyproject.toml,
`uv sync` would try to resolve `noise` and die before we could do anything.

So: sync the well-behaved deps first, satisfy `noise` (real package if it
builds, otherwise our pure-Python shim), then add raenim with --no-deps.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

MANIM_PIN = "manim==0.20.1"  # raenim was developed against 0.20.x; 0.21 is unverified
RAENIM_GIT = "git+https://github.com/CodingVillainKor/raenim.git"
DEPS = [MANIM_PIN, "addict>=2.4.0", "opencv-python>=4.12.0.88", "numpy>=1.26", "PyMuPDF>=1.24"]

PYPROJECT = """\
[project]
name = "{name}"
version = "0.1.0"
description = "Manim video project generated by paper-to-manim-video"
requires-python = ">=3.11,<3.12"
dependencies = [
{deps}
]
"""


def log(step: str, msg: str) -> None:
    print(f"[{step}] {msg}", flush=True)


def run(cmd: list[str], cwd: Path | None = None, check: bool = True) -> subprocess.CompletedProcess:
    print(f"  $ {' '.join(cmd)}", flush=True)
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if proc.stdout.strip():
        print("\n".join("    " + ln for ln in proc.stdout.strip().splitlines()[-25:]), flush=True)
    if proc.returncode != 0:
        if proc.stderr.strip():
            print("\n".join("    ! " + ln for ln in proc.stderr.strip().splitlines()[-25:]), flush=True)
        if check:
            raise SystemExit(f"command failed with exit {proc.returncode}")
    return proc


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", text).strip("-").lower()
    return slug or "video-project"


def site_packages(root: Path) -> Path:
    """Locate the venv's site-packages (Windows: Lib/site-packages, POSIX: lib/pythonX.Y/site-packages)."""
    win = root / ".venv" / "Lib" / "site-packages"
    if win.is_dir():
        return win
    for cand in sorted((root / ".venv" / "lib").glob("python3.*/site-packages")):
        return cand
    raise SystemExit(f"could not locate site-packages under {root / '.venv'}")


def venv_python(root: Path) -> Path:
    win = root / ".venv" / "Scripts" / "python.exe"
    return win if win.exists() else root / ".venv" / "bin" / "python"


def ensure_noise(root: Path, shim_src: Path) -> str:
    """Return 'real', 'shim', or raise. Tries the C extension first."""
    log("noise", "trying the real `noise` package (needs a C compiler)...")
    proc = run(["uv", "pip", "install", "noise"], cwd=root, check=False)
    if proc.returncode == 0:
        check = run([str(venv_python(root)), "-c", "import noise; print(noise.__file__)"],
                    cwd=root, check=False)
        if check.returncode == 0:
            log("noise", "real package installed")
            return "real"

    log("noise", "build failed or unimportable — installing pure-Python shim instead")
    if not shim_src.is_file():
        raise SystemExit(f"shim missing: {shim_src}")
    dest = site_packages(root) / "noise.py"
    shutil.copyfile(shim_src, dest)
    log("noise", f"shim -> {dest}")
    return "shim"


def main() -> int:
    ap = argparse.ArgumentParser(description="Bootstrap a Manim video project environment")
    ap.add_argument("--root", required=True, help=r"project root, ASCII path (e.g. C:\manimwork\my-paper)")
    ap.add_argument("--force", action="store_true", help="recreate pyproject.toml even if present")
    ap.add_argument("--json", action="store_true", help="emit a machine-readable summary on the last line")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    skill_dir = Path(__file__).resolve().parent.parent
    shim_src = skill_dir / "assets" / "noise_shim" / "noise.py"

    if not root.as_posix().isascii():
        print(f"WARNING: project root is not ASCII ({root}). MiKTeX and some tooling "
              f"mishandle non-ASCII paths; C:\\manimwork\\<slug> is recommended.", flush=True)

    if shutil.which("uv") is None:
        raise SystemExit("uv not found on PATH. Install from https://docs.astral.sh/uv/")

    log("init", f"project root: {root}")
    root.mkdir(parents=True, exist_ok=True)

    pyproject = root / "pyproject.toml"
    if args.force or not pyproject.exists():
        pyproject.write_text(
            PYPROJECT.format(
                name=slugify(root.name),
                deps="\n".join(f'    "{d}",' for d in DEPS),
            ),
            encoding="utf-8",
        )
        log("init", f"wrote {pyproject.name}")
    else:
        log("init", "pyproject.toml exists, keeping it (use --force to overwrite)")

    log("sync", "resolving and installing base dependencies (this pulls manim + torch-free deps)")
    run(["uv", "sync"], cwd=root)

    noise_mode = ensure_noise(root, shim_src)

    log("raenim", "installing with --no-deps (its setup.py would drag in `noise`)")
    run(["uv", "pip", "install", "--no-deps", RAENIM_GIT], cwd=root)

    log("smoke", "importing manim + raenim in the project venv")
    smoke = run(
        [str(venv_python(root)), "-c",
         "import manim, raenim, noise;"
         "from manim import Scene, MathTex, Text;"
         "from raenim import Scene2D, Scene3D, PythonCode, RaeTex, Tensor;"
         "print('manim', manim.__version__);"
         "print('noise_shim', getattr(noise, 'SHIM', False));"
         "print('OK')"],
        cwd=root, check=False,
    )
    ok = smoke.returncode == 0 and "OK" in smoke.stdout

    summary = {
        "root": str(root),
        "python": str(venv_python(root)),
        "noise": noise_mode,
        "manim_pin": MANIM_PIN,
        "import_smoke": "pass" if ok else "fail",
    }
    log("done", "environment ready" if ok else "environment INCOMPLETE — see errors above")
    if args.json:
        print(json.dumps(summary, ensure_ascii=False))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
