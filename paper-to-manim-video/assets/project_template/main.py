"""{{VIDEO_TITLE}}

Generated by paper-to-manim-video. One class per segment of the episode;
render a segment with its class name (never bare `manim main.py` — with several
classes in one file Manim stops and asks interactively).

    uv run manim -ql main.py intro      # smoke
    uv run manim -qh main.py intro      # final

Timing contract: `playw` plays THEN waits, so a shot lasts run_time + wait.
The generator sets wait = max(0.2, est_sec - run_time) so the segment length
matches the narration read time recorded in shots.json.
"""

from manim import *
from raenim import *
from random import seed

seed(41)
np.random.seed(41)

# Korean must name a font explicitly — Pango will not pick one for us.
KR = "Malgun Gothic"


def kr(text: str, **kwargs) -> Text:
    """Korean text with the project font applied."""
    kwargs.setdefault("font", KR)
    return Text(text, **kwargs)


class intro(Scene2D):
    def construct(self):
        title = kr("{{VIDEO_TITLE}}", font_size=48)
        self.playw(Write(title), run_time=1.5, wait=1.0)
        self.playw(title.animate.scale(0.6).to_edge(UP), run_time=1.0, wait=0.5)
