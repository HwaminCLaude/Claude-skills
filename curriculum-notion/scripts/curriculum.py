def build() -> dict:
    units = []
    prev_id = None
    for w in sorted(U):
        for i, (title, kind, level, mins, goal) in enumerate(U[w], start=1):
            uid = f"W{w:02d}U{i:02d}"
            units.append({
                "id": uid,
                "week": w,
                "order": i,
                "title": f"{i:02d} · {title}",
                "raw_title": title,
                "type": kind,
                "level": level,
                "minutes": mins,
                "goal": goal,
                # 선수지식: 기본은 바로 앞 유닛 (필요한 때 바로 앞 원칙)
                "prereq": [prev_id] if prev_id else [],
                "week_folder": WEEKS[w],
                "notebook": f"{uid}_{title.split(' — ')[0].replace(' ', '_')}.ipynb",
            })
            prev_id = uid
    return {
        "db_id": os.environ.get("CURRICULUM_DB_ID", ""),
        "data_source_id": os.environ.get("CURRICULUM_DS_ID", ""),
        "drive_root": "메타코드 실습프로젝트",
        "notebook_drive_dir": "메타코드 실습프로젝트/_코딩북_실습",
        "weeks": [{"week": w, "folder": WEEKS[w], "intro": WEEK_INTRO[w],
                   "n_units": len(U[w])} for w in sorted(U)],
        "units": units,
    }


def validate(c: dict) -> list[str]:
    errs = []
    ids = [u["id"] for u in c["units"]]
    if len(ids) != len(set(ids)):
        errs.append("중복 유닛 id")
    if set(c.keys()) < {"db_id", "data_source_id", "weeks", "units"}:
        errs.append("최상위 키 누락")
    for u in c["units"]:
        if u["type"] not in ("개념", "실습", "보충", "프로젝트"):
            errs.append(f'{u["id"]} 유형 이상: {u["type"]}')
        if u["level"] not in ("입문", "기본", "심화"):
            errs.append(f'{u["id"]} 난이도 이상: {u["level"]}')
        if not u["goal"].endswith((".", "다.")):
            errs.append(f'{u["id"]} 목표 문장 형식')
        for p in u["prereq"]:
            if p not in ids:
                errs.append(f'{u["id"]} 선수지식 {p} 없음')
    for wk in c["weeks"]:
        got = sum(1 for u in c["units"] if u["week"] == wk["week"])
        if got != wk["n_units"]:
            errs.append(f'{wk["week"]}주차 유닛 수 불일치 {got}≠{wk["n_units"]}')
    return errs


def main() -> int:
    c = build()
    errs = validate(c)
    tot = len(c["units"])
    print(f"주차 {len(c['weeks'])}개 / 유닛 {tot}개 / 총 {sum(u['minutes'] for u in c['units'])/60:.0f}시간")
    from collections import Counter
    print("  유형:", dict(Counter(u["type"] for u in c["units"])))
    print("  난이도:", dict(Counter(u["level"] for u in c["units"])))
    for wk in c["weeks"]:
        print(f"  {wk['week']:>2}주차 {wk['n_units']}유닛  {wk['folder']}")
    if errs:
        print("\n[검증 실패]")
        for e in errs:
            print("  -", e)
        return 1
    print("\n검증 통과")
    if "--dump" in sys.argv:
        OUT.write_text(json.dumps(c, ensure_ascii=False, indent=1), encoding="utf-8")
        print("저장:", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
